OPEN_WUJI_QPOS = np.zeros((WUJI_QPOS_DIM,), dtype=np.float32)


def build_initial_sonic_action(
    *,
    left_wuji_qpos: np.ndarray | None = None,
    right_wuji_qpos: np.ndarray | None = None,
) -> SonicAction:
    token = np.asarray(LATENT_INITIAL_MOTION_TOKEN, dtype=np.float32).reshape(-1)
    if token.size != TOKEN_DIM:
        raise ValueError(f"initial token dim {token.size}, expected {TOKEN_DIM}")

    left = OPEN_WUJI_QPOS if left_wuji_qpos is None else left_wuji_qpos
    right = OPEN_WUJI_QPOS if right_wuji_qpos is None else right_wuji_qpos
    return SonicAction(
        token_state=token.copy(),
        left_wuji_qpos=apply_wuji_qpos_limits(left),
        right_wuji_qpos=apply_wuji_qpos_limits(right),
    )


def summarize_initial_sonic_action(*, preview: int = 8) -> str:
    action = build_initial_sonic_action()
    token = action.token_state
    head = ", ".join(f"{value:.4f}" for value in token[:preview])
    return (
        f"token_dim={token.size} min={float(np.min(token)):.4f} "
        f"max={float(np.max(token)):.4f} mean={float(np.mean(token)):.4f} "
        f"head=[{head}] left_hand_dim={action.left_wuji_qpos.size} "
        f"right_hand_dim={action.right_wuji_qpos.size}"
    )
